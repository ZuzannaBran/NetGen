/**
 * Escape untrusted values before interpolating them into an HTML template.
 * For DOM-only updates, prefer textContent instead of innerHTML.
 */
export function escapeHtml(value) {
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
